from tabulate import tabulate

def to_matrix(byte_list):
    matrix_byte = [[0]*4 for _ in range(4)]
    for col in range(4):
        for row in range(4):
            matrix_byte[row][col] = byte_list[col * 4 + row]
    return matrix_byte

def xor_matrix(a,b):
    new_matrix = [[0]*4 for _ in range(4)]
    for col in range(4):
        for row in range(4):
            new_matrix[row][col] = a[row][col] ^ b[row][col]
    return new_matrix

